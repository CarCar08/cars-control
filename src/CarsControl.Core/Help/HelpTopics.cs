namespace CarsControl.Core.Help;

/// <summary>
/// One explainer behind a (?) button: what the thing is, what C.A.R.S. does with it, what you should do, and whether it's
/// safe and undoable. Written for someone who has never heard the word before.
/// </summary>
public sealed record HelpTopic(string Id, string Title, string What, string Does, string ToDo, string Safety)
{
    /// <summary>Words the command palette matches ("what is pawnio").</summary>
    public string SearchText => $"{Title} {Id.Replace('-', ' ')}";

    /// <summary>The same explainer for a PC without Salad: its mentions are dropped and the sentences stay grammatical.</summary>
    public HelpTopic ForPc(bool saladInstalled) => saladInstalled ? this : this with
    {
        What = WithoutSalad(What), Does = WithoutSalad(Does), ToDo = WithoutSalad(ToDo), Safety = WithoutSalad(Safety),
    };

    internal static string WithoutSalad(string text) => text
        .Replace("Windows, security software, remote access and Salad are", "Windows, security software and remote access are")
        .Replace("notifications, other apps and Salad are", "notifications and other apps are")
        .Replace("remote access, graphics driver services and Salad are", "remote access and graphics driver services are");
}

