public class WizTreeImportTests
{
    // Shape of a real WizTree 4.33 export (verified on this PC), shortened. movie.mkv is an online-only
    // iCloud placeholder (attributes 0x501620): full Size, nothing Allocated.
    private const string Csv = """
        Generated by WizTree 4.33 10/12/2026 12:29:05 AM (You can hide this message by making a donation)
        File Name,Size,Allocated,Modified,Attributes,Files,Folders,DRIVECAPACITY,FREESPACE,USEDSPACE,RESERVEDSPACE
        "X:\",1250,1000,2026/10/12 00:12:45,0,5,3,5000,4000,1000,0
        "X:\Games\",800,800,2026/10/12 00:12:45,16,2,1,
        "X:\Games\Big Game, Deluxe\",700,700,2026/10/12 00:12:45,16,1,0,
        "X:\Games\Big Game, Deluxe\data.pak",700,700,2025/01/01 10:00:00,32,0,0
        "X:\Games\readme.txt",100,100,2026/10/12 00:12:45,32,0,0
        "X:\Users\",400,150,2026/10/12 00:12:45,16,2,0,
        "X:\Users\video ""final"".mp4",150,150,2024/03/03 09:00:00,32,0,0
        "X:\Users\movie.mkv",250,0,2026/09/01 00:00:00,5248544,0,0
        "X:\root.log",50,50,2026/10/12 00:12:45,32,0,0
        """;

    [Fact]
    public void Counts_space_on_disk_not_online_only_cloud_files() // A: showed 1.3 TB on a drive with 0.97 TB in use
    {
        var r = WizTreeImport.Parse(new StringReader(Csv), @"X:\", TimeSpan.Zero);
        Assert.Equal(150, r.Root.Children[1].TotalBytes); // Users: 400 listed, 150 on disk
        Assert.Equal(250, r.OnlineOnlyBytes);
        Assert.DoesNotContain(r.Largest, f => f.Path.EndsWith("movie.mkv"));
    }

    [Fact]
    public void Builds_tree_from_recursive_folder_totals()
    {
        var r = WizTreeImport.Parse(new StringReader(Csv), @"X:\", TimeSpan.Zero);
        Assert.Equal(1000, r.Root.TotalBytes);
        Assert.Equal(1000, r.DriveUsedBytes);
        Assert.Equal("Fast scan (MFT)", r.Method);
        Assert.Equal(["Games", "Users"], r.Root.Children.Select(c => c.Name));
        var games = r.Root.Children[0];
        Assert.Equal(800, games.TotalBytes);
        Assert.Equal(100, games.OwnFilesBytes);              // 800 - 700 in the subfolder
        Assert.Equal("Big Game, Deluxe", games.Children[0].Name); // comma inside quotes
        Assert.Equal(50, r.Root.OwnFilesBytes);               // root.log
        Assert.Equal(@"X:\Games\Big Game, Deluxe", games.Children[0].FullPath);
    }

    [Fact]
    public void Tracks_largest_and_stale_files()
    {
        var r = WizTreeImport.Parse(new StringReader(Csv), @"X:\", TimeSpan.Zero);
        Assert.Equal(@"X:\Games\Big Game, Deluxe\data.pak", r.Largest[0].Path);
        Assert.Contains(r.Largest, f => f.Path.EndsWith("video \"final\".mp4")); // doubled quotes
    }

    [Fact]
    public void Rejects_files_that_are_not_wiztree_exports() =>
        Assert.Throws<InvalidDataException>(() => WizTreeImport.Parse(new StringReader("hello\nworld"), @"X:\", TimeSpan.Zero));
}

public class ScanCacheTests
{
    [Fact]
    public void Round_trips_and_truncates_below_max_depth()
    {
        var root = new DirNode(@"Q:\", null) { TotalBytes = 100, TotalFiles = 10 };
        var node = root;
        for (var depth = 1; depth <= ScanCache.MaxDepth + 2; depth++)
        {
            var child = new DirNode($"L{depth}", node) { TotalBytes = 100 - depth, TotalFiles = 10 - depth };
            node.Children.Add(child);
            node = child;
        }
        var saved = ScanCache.ToNode(root, 0);
        var back = ScanCache.FromNode(saved, null, @"Q:\");

        var n = back;
        for (var depth = 1; depth <= ScanCache.MaxDepth; depth++) n = n.Children.Single();
        Assert.True(n.Truncated);          // deeper folders weren't kept…
        Assert.Empty(n.Children);          // …so drilling in rescans that folder
        Assert.Equal(100 - ScanCache.MaxDepth, n.TotalBytes);
    }
}

public class FileOwnershipTests
{
    private static readonly string Local = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
    private static readonly string ProgramData = Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData);

    [Fact]
    public void Files_inside_an_installed_app_or_game_cannot_be_recycled()
    {
        var game = new GameEntry("Apex Legends", "Steam", @"C:\Steam", @"D:\Steam\steamapps\common\Apex Legends", 1, null, null, "1172470");
        var o = new FileOwnership([], [game]).Classify(@"D:\Steam\steamapps\common\Apex Legends\paks\pc_all.opt.starpak");
        Assert.Equal(OwnerKind.InstalledApp, o.Kind);
        Assert.False(o.CanRecycle);
        Assert.Contains("Apex Legends", o.Text);
    }

    [Fact]
    public void ProgramData_is_off_limits() // Salad's 113 GB WSL disk lives there
    {
        var o = new FileOwnership([], []).Classify(Path.Combine(ProgramData, @"Salad\wsl\ext4.vhdx"));
        Assert.Equal(OwnerKind.System, o.Kind);
        Assert.False(o.CanRecycle);
    }

    [Fact]
    public void App_data_is_allowed_with_a_warning_even_for_unregistered_apps() // LTX Desktop has no ARP entry
    {
        var o = new FileOwnership([], []).Classify(Path.Combine(Local, @"LTXDesktop\models\big.safetensors"));
        Assert.Equal(OwnerKind.AppData, o.Kind);
        Assert.True(o.CanRecycle);
        Assert.Contains("LTXDesktop", o.Text);
    }

    [Fact]
    public void Temp_files_are_free() =>
        Assert.Equal(OwnerKind.Free, new FileOwnership([], []).Classify(Path.Combine(Local, @"Temp\setup.iso")).Kind);
}

public class SteamPlaytimeTests
{
    [Fact]
    public void Reads_last_played_and_minutes_and_merges_accounts()
    {
        const string vdf = """
            "UserLocalConfigStore" { "Software" { "Valve" { "Steam" { "apps" {
              "271590" { "LastPlayed" "1753056000" "Playtime" "6000" }
              "1172470" { "LastPlayed" "1759968000" "Playtime" "120" }
            } } } } }
            """;
        const string second = """
            "UserLocalConfigStore" { "Software" { "Valve" { "Steam" { "apps" { "271590" { "LastPlayed" "1700000000" "Playtime" "9000" } } } } } }
            """;
        var d = new Dictionary<string, (DateTime? LastPlayed, int Minutes)>();
        GameLibraries.MergePlaytime(d, Vdf.Parse(vdf));
        GameLibraries.MergePlaytime(d, Vdf.Parse(second));
        Assert.Equal(9000, d["271590"].Minutes);                                   // max across accounts
        Assert.Equal(DateTimeOffset.FromUnixTimeSeconds(1753056000).LocalDateTime, d["271590"].LastPlayed); // latest play
        Assert.Equal(120, d["1172470"].Minutes);
    }
}

public class InventoryCarryOverTests
{
    [Fact]
    public void Reuses_fresh_sizes_only_for_unchanged_versions()
    {
        AppEntry A(string key, string ver, long? size = null, DateTime? at = null) => new()
        {
            Key = key, Name = key, Version = ver, Source = AppSource.Arp, SizeBytes = size, SizeIsMeasured = size is not null, SizeMeasuredAt = at,
        };
        var old = new[] { A("a", "1", 100, DateTime.Now.AddDays(-1)), A("b", "1", 200, DateTime.Now.AddDays(-1)), A("c", "1", 300, DateTime.Now.AddDays(-30)) };
        var fresh = new[] { A("a", "1"), A("b", "2"), A("c", "1") };
        Assert.Equal(1, InventoryService.CarryOverSizes(fresh, old));
        Assert.Equal(100, fresh[0].SizeBytes);   // same version, measured yesterday
        Assert.Null(fresh[1].SizeBytes);         // updated: re-measure
        Assert.Null(fresh[2].SizeBytes);         // measurement too old
    }
}

public class StorageHelperValidationTests
{
    [Theory]
    [InlineData("C", true)]
    [InlineData("a", true)]
    [InlineData("C:", false)]
    [InlineData("..", false)]
    [InlineData("", false)]
    [InlineData("C & calc", false)]
    public void Drive_letters(string drive, bool ok) => Assert.Equal(ok, StorageOps.IsValidDrive(drive));

    [Fact]
    public async Task Helper_rejects_non_letter_drives()
    {
        var ops = new HelperOperations(new HelperLog(), null);
        var r = await ops.ExecuteAsync(new StorageScanOp(@"C:\Windows"), dryRun: true, _ => { }, default);
        Assert.Equal(OpStatus.Rejected, r.Status);
    }
